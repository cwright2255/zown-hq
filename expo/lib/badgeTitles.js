// lib/badgeTitles.js
//
// The names of the 300 achievements and of Battle Pass tiers 21 to 100, written by hand. Every name is about something the app really
// has: workouts, streaks, calories, XP and levels, hikes and trail miles, virtual races, journeys, the Battle Pass, and the exercises
// in the library (a squat, a press, a plank, a lunge). The app has no swimming, boxing, fencing, skiing and so on, so a badge that
// shows one of those sports never names it: it winks at it with an idiom about something in the app instead (a swimmer on a finished
// virtual race is "Going Swimmingly"; a ski slope on 400 trail miles is "Uphill Both Ways"). The descriptions stay plain, so what an
// achievement asks for is never hidden behind the joke.
//
// They are keyed by id (achievements) and tier number, and written for the icon each one is given in lib/achievementCatalogue.js and
// lib/battlePassTiers.js: if an icon is changed, change its name here too. __tests__/badgeTitles.test.js fails when one is missing,
// used twice, too long to fit its card, or names a sport the app does not have. Tiers 1 to 20 are real rewards (themes, XP, a
// discount) and keep their plain names. Pure data, no React, no Firebase.

